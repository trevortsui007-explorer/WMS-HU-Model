param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$source = Join-Path $root 'WMS/Modules'
$destination = Join-Path $root 'WMS/Host.Modules'
$files = @(Get-ChildItem -LiteralPath $source -Filter '*.cs' -File -Recurse)
if (!$files.Count) { throw 'No Learun modules found.' }
if (!$Check) { New-Item -ItemType Directory -Path $destination -Force | Out-Null }
foreach ($file in $files) {
    $relative = $file.FullName.Substring($source.Length + 1)
    if ($relative -match '^Portal[\\/]') { throw 'Portal is reserved for standalone code.' }
    $text = [IO.File]::ReadAllText($file.FullName).Replace("`r`n", "`n")
    if ($text -notmatch ':\s*BaseApi\b') { throw "Unexpected base class: $($file.Name)" }
    $text = $text -replace '(?m)^using Learun\.Application\.WebApi;\s*\n', ''
    $text = $text.Replace('namespace WMS.Modules', 'namespace WMS.Host.Modules')
    $text = $text -replace ':\s*BaseApi\b', ': NancyModule'
    $text = $text.Replace('Logger.Error(', 'System.Diagnostics.Trace.TraceError("{0}", ')
    if ($text -match 'Learun\.|\buserInfo\b|\bBaseApi\b') { throw "Host-specific dependency requires manual adaptation: $($file.Name)" }
    # The legacy health response contains an outdated literal; keep Learun source untouched.
    if ($file.Name -eq 'HealthModule.cs') { $text = $text.Replace('.NET Framework 4.7.2', '.NET Framework 4.6.1') }
    $text = "// Generated by Build/Sync-HostModules.ps1. Edit WMS/Modules, then synchronize.`n" + $text
    $target = Join-Path $destination $relative
    if (!$Check) { New-Item -ItemType Directory -Path (Split-Path $target -Parent) -Force | Out-Null }
    if ($Check) {
        if (!(Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target).Replace("`r`n", "`n") -cne $text) {
            throw "Host module out of sync: $($file.Name). Run Build/Sync-HostModules.ps1."
        }
    } else { [IO.File]::WriteAllText($target, $text, (New-Object Text.UTF8Encoding($true))) }
}
$relativeFiles = @($files | ForEach-Object { $_.FullName.Substring($source.Length + 1) })
$extra = @(Get-ChildItem -LiteralPath $destination -Filter '*.cs' -File -Recurse | Where-Object {
    $relative = $_.FullName.Substring($destination.Length + 1)
    $relative -notmatch '^Portal[\\/]' -and $relative -notin $relativeFiles
})
if ($extra.Count) { throw 'Unexpected Host.Modules files: remove obsolete counterparts explicitly.' }
Write-Host "Host modules verified: $($files.Count)"
